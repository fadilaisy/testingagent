// PostgreSQL in production (DATABASE_URL, through `pg`), and PGlite, the same
// Postgres compiled to WebAssembly, for local development and tests so they
// stay zero-setup. Geo queries still use a bounding-box prefilter plus
// haversine in JS (see geo.js); PostGIS can replace that later without
// changing the table shapes.
//
// Every call is async. Statements keep SQLite-style `?` placeholders, which
// are rewritten to $1, $2, ... before they reach Postgres.

// Timestamps stay ISO-8601 text (as in the SQLite days), so they sort and
// compare as strings and come back to JS unchanged.
export const NOW_SQL = `to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;


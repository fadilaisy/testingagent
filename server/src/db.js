// Rewrites ? placeholders to $1, $2, ... (and numbered ?1 to $1), leaving
// quoted strings and identifiers alone.
export function toPg(sql) {
  let out = '';
  let n = 0;
  let quote = null;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (quote) {
      if (ch === quote) quote = null;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
    } else if (ch === '?') {
      const digits = /^\d+/.exec(sql.slice(i + 1))?.[0];
      if (digits) {
        out += `$${digits}`;
        i += digits.length;
      } else {
        out += `$${++n}`;
      }
      continue;
    }
    out += ch;
  }
  return out;
}

// node:sqlite accepted undefined as NULL; keep that behaviour.
const clean = (params) => params.map((p) => (p === undefined ? null : p));

// One database handle: a pg Pool, a PGlite instance or a transaction on
// either. `query(text, params)` must resolve to { rows, rowCount }.
function wrap(query, extra = {}) {
  return {
    query,
    prepare(sql) {
      const text = toPg(sql);
      return {
        async get(...params) {
          return (await query(text, clean(params))).rows[0];
        },
        async all(...params) {
          return (await query(text, clean(params))).rows;
        },
        // `changes` mirrors node:sqlite's run() result.
        async run(...params) {
          const r = await query(text, clean(params));
          return { changes: r.rowCount ?? r.affectedRows ?? 0 };
        },
      };
    },
    ...extra,
  };
}

// Bigint counts and numeric sums come back as numbers, like they did from
// SQLite. Every count Roamr makes fits easily in a double.
const INT8 = 20;
const NUMERIC = 1700;
const toNumber = (v) => (v === null ? null : Number(v));

async function openPg(url) {
  const { default: pg } = await import('pg');
  pg.types.setTypeParser(INT8, toNumber);
  pg.types.setTypeParser(NUMERIC, toNumber);
  const pool = new pg.Pool({ connectionString: url, max: 10 });
  return wrap((text, params) => pool.query(text, params), {
    async exec(sql) {
      await pool.query(sql);
    },
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const tx = wrap((t, p) => client.query(t, p), { exec: (sql) => client.query(sql) });
        const result = await fn(tx);
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK');
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  });
}

async function openPglite(dir) {
  const { PGlite } = await import('@electric-sql/pglite');
  if (dir === ':memory:') dir = undefined;
  if (dir) fs.mkdirSync(path.dirname(dir), { recursive: true });
  const lite = new PGlite(dir || undefined, { parsers: { [INT8]: toNumber, [NUMERIC]: toNumber } });
  return wrap((text, params) => lite.query(text, params), {
    async exec(sql) {
      await lite.exec(sql);
    },
    transaction(fn) {
      return lite.transaction((tx) => fn(wrap((t, p) => tx.query(t, p), { exec: (sql) => tx.exec(sql) })));
    },
    close: () => lite.close(),
  });
}

// target: a postgres:// URL, a folder for a PGlite database, or nothing (or
// ':memory:') for a throwaway in-memory database (tests).
export async function openDb(target) {
  const db = /^postgres(ql)?:\/\//.test(target ?? '') ? await openPg(target) : await openPglite(target);
  await db.exec(SCHEMA);
  return db;
}

// Runs fn(tx) inside a transaction, rolling back if it throws. Use only tx
// inside fn: queries through the outer handle run outside the transaction
// (and on PGlite wait until it ends, so they would hang).
export function transaction(db, fn) {
  return db.transaction(fn);
}

